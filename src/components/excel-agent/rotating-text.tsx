interface RotatingTextProps {
  interval?: number; // milliseconds between word changes
  className?: string;
}

export function RotatingText({ interval = 2000, className = '' }: RotatingTextProps) {
  const [currentIndex, setCurrentIndex] = useState(0);
  const [isVisible, setIsVisible] = useState(true);

  useEffect(() => {
    const rotateTimer = setInterval(() => {
      // Fade out
      setIsVisible(false);

      // Wait for fade out, then change word and fade in
      setTimeout(() => {
        setCurrentIndex((prev) => {
          // Generate random index
          let newIndex = Math.floor(Math.random() * LOADING_WORDS.length);

          // Ensure we don't repeat the same word twice in a row
          while (newIndex === prev && LOADING_WORDS.length > 1) {
            newIndex = Math.floor(Math.random() * LOADING_WORDS.length);
          }

          return newIndex;
        });
        setIsVisible(true);
      }, 300); // Half of the transition duration
    }, interval);

    return () => clearInterval(rotateTimer);
  }, [interval]);

  return (
    <>
      <style>{`
        @keyframes gradient-shift {
          0% {
            background-position: 0% 50%;
          }
          50% {
            background-position: 100% 50%;
          }
          100% {
            background-position: 0% 50%;
          }
        }

        .rotating-gradient-text {
          background: linear-gradient(90deg, #a855f7, #3b82f6, #10b981, #f59e0b, #a855f7);
          background-size: 300% 100%;
          -webkit-background-clip: text;
          -webkit-text-fill-color: transparent;
          background-clip: text;
          animation: gradient-shift 8s ease infinite;
          font-weight: 600;
        }
      `}</style>
      <span
        className={`inline-block transition-opacity duration-500 rotating-gradient-text ${
          isVisible ? 'opacity-100' : 'opacity-0'
        } ${className}`}
      >
        {LOADING_WORDS[currentIndex]}...
      </span>
    </>
  );
}
